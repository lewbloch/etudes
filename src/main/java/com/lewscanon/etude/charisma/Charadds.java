package com.lewscanon.etude.charisma;

public class Charadds {
    public static void main(String... args) {
        final char three = '３';
        final char two = '２';
        System.out.printf("three + two = %d\n", three + two);

        final char ayy = 'A';
        final char bey = ayy + 1;
        System.out.printf("bey = %c\n", bey);
    }
}
